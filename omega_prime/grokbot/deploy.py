"""Deployment kit: render hardened artifacts for the Grok Bot tool host and check them.

`render` writes deterministic deployment artifacts for one of four targets
(`docker`, `compose`, `systemd`, `k8s`). Every target runs the host as a
non-root user on a read-only root filesystem with one writable state volume and
`/tmp`, reads its bearer token from a file the platform mounts (a secret is
never written into an artifact), and exposes `/healthz` and `/readyz` for the
platform's probes.

`check` scans rendered or hand-edited artifacts and reports findings with
stable ids (`FINDING_CATALOG`). It is text-based and stdlib-only: YAML files are
read with a small block-YAML subset reader, so no PyYAML is needed at runtime.

CLI: `python -m omega_prime.grokbot.deploy render|check|healthcheck|promote ...`.
"""

