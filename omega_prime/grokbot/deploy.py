def _health_code(port: int) -> str:
    """Stdlib-only liveness probe used by Docker and compose healthchecks."""
    return (
        "import sys, urllib.request; "
        f"sys.exit(0 if urllib.request.urlopen('http://127.0.0.1:{port}/healthz', "
        "timeout=3).status == 200 else 1)"
    )


