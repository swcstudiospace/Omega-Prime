_SECRET_SUFFIXES = (
    "token",
    "secret",
    "password",
    "passwd",
    "apikey",
    "api_key",
    "api-key",
    "private_key",
    "access_key",
    "secret_key",
    "_key",
)
_FALSEY = {"true", "false", "null", "none", "yes", "no", "on", "off", "~", ""}
_TOKEN_PATTERNS: tuple[tuple[str, re.Pattern[str]], ...] = (
    (
        "a GitHub token",
        re.compile(r"\b(?:gh[pousr]_[A-Za-z0-9]{20,}|github_pat_\w{20,})"),
    ),
    ("a GitLab token", re.compile(r"\bglpat-[A-Za-z0-9_-]{16,}")),
    ("an API key", re.compile(r"\bsk-[A-Za-z0-9_-]{20,}")),
    ("a Slack token", re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}")),
    ("an AWS access key", re.compile(r"\bAKIA[0-9A-Z]{16}\b")),
    ("a JWT", re.compile(r"\beyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]+")),
    ("a private key", re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----")),
    (
        "a hex secret",
        re.compile(r"(?<![A-Za-z0-9:@/_.-])[0-9a-fA-F]{32,}(?![A-Za-z0-9])"),
    ),
)


def _secret_key(key: str) -> bool:
    return key.lower().endswith(_SECRET_SUFFIXES)


def _literal_value(value: Any) -> bool:
    """True when `value` is a concrete value rather than a reference or a flag."""
    if value is None or isinstance(value, bool):
        return False
    text = str(value).strip()
    if text.lower() in _FALSEY or _INT_RE.match(text):
        return False
    return not text.startswith(("$", "%", "/", "file:", "<", "secret:"))


class _Report:
    def __init__(self, file: str) -> None:
        self.file = file
        self.findings: list[Finding] = []
        self._seen: set[tuple[str, str]] = set()

    def add(self, finding_id: str, message: str) -> None:
        if (finding_id, message) in self._seen:
            return
        self._seen.add((finding_id, message))
        self.findings.append(
            Finding(finding_id, FINDING_CATALOG[finding_id][0], self.file, message)
        )

    def secret_env(self, where: str, key: str, value: Any) -> None:
        if _secret_key(key) and _literal_value(value):
            self.add("inline-secret", f"{where}: {key} is set to a literal value")

    def secret_args(self, where: str, tokens: Sequence[str]) -> None:
        for index, token in enumerate(tokens):
            if token.startswith("--token=") or (
                token == "--token"
                and index + 1 < len(tokens)
                and _literal_value(tokens[index + 1])
            ):
                self.add("inline-secret", f"{where}: --token carries a literal value")

    def scan_text(self, text: str) -> None:
        for line in text.splitlines():
            code = line.strip()
            if not code or code.startswith("#"):
                continue
            for kind, pattern in _TOKEN_PATTERNS:
                if pattern.search(code):
                    self.add(
                        "inline-secret", f"the file contains what looks like {kind}"
                    )


def _words(value: Any) -> list[str]:
    if isinstance(value, list):
        return [str(x) for x in value]
    if isinstance(value, str):
        try:
            return shlex.split(value)
        except ValueError:
            return value.split()
    return []


def _image_findings(report: _Report, where: str, ref: str) -> None:
    if "$" in ref or ref == "scratch" or "@sha256:" in ref:
        return
    last = ref.rsplit("/", 1)[-1]
    tag = last.split(":", 1)[1] if ":" in last else ""
    if not tag or tag == "latest":
        report.add("latest-tag", f"{where}: image {ref!r} is untagged or `latest`")


# --- Dockerfile


def _docker_instructions(text: str) -> list[tuple[str, str]]:
    result: list[tuple[str, str]] = []
    buffer = ""
    for raw in text.splitlines():
        stripped = raw.strip()
        if stripped.startswith("#") or (not stripped and not buffer):
            continue
        if stripped.endswith("\\"):
            buffer += stripped[:-1] + " "
            continue
        full = (buffer + stripped).strip()
        buffer = ""
        if full:
            keyword, _, args = full.partition(" ")
            result.append((keyword.upper(), args.strip()))
    if buffer.strip():
        keyword, _, args = buffer.strip().partition(" ")
        result.append((keyword.upper(), args.strip()))
    return result


def _exec_words(args: str) -> list[str]:
    if args.startswith("["):
        try:
            parsed = json.loads(args)
        except ValueError:
            return []
        return [str(x) for x in parsed] if isinstance(parsed, list) else []
    return _words(args)


def _check_docker(text: str, report: _Report) -> None:
    stages: list[dict[str, Any]] = []
    aliases: dict[str, dict[str, Any]] = {}
    for keyword, args in _docker_instructions(text):
        if keyword == "FROM":
            parts = [p for p in args.split() if not p.startswith("--")]
            if not parts:
                continue
            ref = parts[0]
            stage: dict[str, Any] = {"user": None, "health": False, "ref": ref}
            parent = aliases.get(ref.lower())
            if parent is not None:
                stage["user"], stage["health"] = parent["user"], parent["health"]
            else:
                _image_findings(report, "FROM", ref)
            if len(parts) >= 3 and parts[1].upper() == "AS":
                aliases[parts[2].lower()] = stage
            stages.append(stage)
            continue
        if not stages:
            continue
        stage = stages[-1]
        if keyword == "USER":
            stage["user"] = args.split()[0] if args.split() else None
        elif keyword == "HEALTHCHECK":
            stage["health"] = not args.upper().startswith("NONE")
        elif keyword in ("ENV", "ARG"):
            try:
                tokens = shlex.split(args)
            except ValueError:
                tokens = args.split()
            if keyword == "ENV" and tokens and "=" not in tokens[0]:
                report.secret_env(keyword, tokens[0], " ".join(tokens[1:]))
            else:
                for token in tokens:
                    key, sep, value = token.partition("=")
                    if sep:
                        report.secret_env(keyword, key, value)
        elif keyword in ("CMD", "ENTRYPOINT"):
            report.secret_args(keyword, _exec_words(args))
    if not stages:
        report.add("unparseable", "no FROM instruction found")
        return
    final = stages[-1]
    user = final["user"]
    if user is None:
        report.add("run-as-root", "no USER instruction in the final stage")
    elif user.split(":")[0] in ("root", "0"):
        report.add("run-as-root", f"the final stage runs as USER {user}")
    if not final["health"]:
        report.add("missing-healthcheck", "the final stage has no HEALTHCHECK")


# --- systemd


def _unit_entries(text: str) -> list[tuple[str, str, str]]:
    entries: list[tuple[str, str, str]] = []
    section = ""
    pending = ""
    for raw in text.splitlines():
        line = raw.strip()
        if pending:
            line = pending + " " + line
            pending = ""
        if not line or line[0] in "#;":
            continue
        if line.endswith("\\"):
            pending = line[:-1].rstrip()
            continue
        if line.startswith("[") and line.endswith("]"):
            section = line[1:-1]
            continue
        key, sep, value = line.partition("=")
        if sep:
            entries.append((section, key.strip(), value.strip()))
    return entries


def _truthy(value: str) -> bool:
    return value.strip().lower() in ("yes", "true", "1", "on")


def _check_systemd(text: str, report: _Report) -> None:
    service = [(k, v) for s, k, v in _unit_entries(text) if s == "Service"]
    last = dict(service)
    user = last.get("User", "")
    if user in ("root", "0") or (not user and not _truthy(last.get("DynamicUser", ""))):
        report.add(
            "run-as-root", "the unit sets no non-root User= and no DynamicUser=yes"
        )
    if not _truthy(last.get("NoNewPrivileges", "")):
        report.add("missing-no-new-privileges", "NoNewPrivileges=yes is not set")
    if last.get("ProtectSystem", "").lower() not in ("strict", "full", "yes", "true"):
        report.add(
            "writable-rootfs", "ProtectSystem is not strict, so / stays writable"
        )
    if not any(k in last for k in ("MemoryMax", "MemoryLimit")):
        report.add("missing-resource-limits", "no MemoryMax= is set")
    for key, value in service:
        if key == "ExecStart":
            words = _words(value.lstrip("@-+!:"))
            report.secret_args("ExecStart", words)
        elif key == "Environment":
            for item in _words(value):
                name, sep, val = item.partition("=")
                if sep:
                    report.secret_env("Environment", name, val)
        elif key == "SetCredential":
            name, _, val = value.partition(":")
            if val:
                report.add(
                    "inline-secret", f"SetCredential= writes {name} into the unit"
                )


# --- compose and Kubernetes


def _env_pairs(env: Any) -> Iterator[tuple[str, Any]]:
    if isinstance(env, dict):
        yield from ((str(k), v) for k, v in env.items())
    elif isinstance(env, list):
        for item in env:
            if isinstance(item, str):
                key, sep, value = item.partition("=")
                if sep:
                    yield key, value


def _compose_user_root(user: Any) -> bool:
    if user is None or user == "":
        return True
    return str(user).split(":")[0] in ("root", "0")


def _has_no_new_privileges(options: Any) -> bool:
    if not isinstance(options, list):
        return False
    for option in options:
        text = str(option).replace("=", ":").lower()
        if text in ("no-new-privileges", "no-new-privileges:true"):
            return True
    return False


def _check_compose(doc: dict[str, Any], report: _Report) -> None:
    services = doc.get("services")
    if not isinstance(services, dict):
        return
    for sname, svc in services.items():
        if not isinstance(svc, dict):
            continue
        where = f"service {sname}"
        image = svc.get("image")
        if isinstance(image, str):
            _image_findings(report, where, image)
        elif "build" not in svc:
            report.add("latest-tag", f"{where}: no image reference")
        if _compose_user_root(svc.get("user")):
            report.add("run-as-root", f"{where}: no non-root `user:` is set")
        if svc.get("privileged") is True:
            report.add("privileged", f"{where}: privileged: true")
        if str(svc.get("network_mode", "")).lower() == "host":
            report.add("host-network", f"{where}: network_mode: host")
        if str(svc.get("pid", "")).lower() == "host":
            report.add("host-pid", f"{where}: pid: host")
        health = svc.get("healthcheck")
        test = health.get("test") if isinstance(health, dict) else None
        disabled = isinstance(health, dict) and (
            health.get("disable") is True or test == ["NONE"] or test == "NONE"
        )
        if not test or disabled:
            report.add("missing-healthcheck", f"{where}: no healthcheck is defined")
        if not _has_no_new_privileges(svc.get("security_opt")):
            report.add(
                "missing-no-new-privileges",
                f"{where}: security_opt lacks no-new-privileges:true",
            )
        if svc.get("read_only") is not True:
            report.add("writable-rootfs", f"{where}: read_only: true is not set")
        deploy = svc.get("deploy")
        limits = (
            deploy.get("resources", {}).get("limits")
            if isinstance(deploy, dict) and isinstance(deploy.get("resources"), dict)
            else None
        )
        if not (
            svc.get("mem_limit") or svc.get("memory") or (limits and "memory" in limits)
        ):
            report.add("missing-resource-limits", f"{where}: no memory limit is set")
        for key, value in _env_pairs(svc.get("environment")):
            report.secret_env(where, key, value)
        report.secret_args(where, _words(svc.get("command")))
        report.secret_args(where, _words(svc.get("entrypoint")))


_WORKLOADS = ("Deployment", "StatefulSet", "DaemonSet", "ReplicaSet", "Job", "Pod")


def _pod_spec(doc: dict[str, Any]) -> dict[str, Any] | None:
    kind = doc.get("kind")
    spec = doc.get("spec")
    if not isinstance(spec, dict):
        return None
    if kind == "Pod":
        return spec
    if kind in _WORKLOADS:
        template = spec.get("template")
        node = template.get("spec") if isinstance(template, dict) else None
        return node if isinstance(node, dict) else None
    if kind == "CronJob":
        job = spec.get("jobTemplate")
        job_spec = job.get("spec") if isinstance(job, dict) else None
        template = job_spec.get("template") if isinstance(job_spec, dict) else None
        node = template.get("spec") if isinstance(template, dict) else None
        return node if isinstance(node, dict) else None
    return None


def _k8s_container(
    report: _Report,
    where: str,
    container: dict[str, Any],
    pod_security: dict[str, Any],
    *,
    probes: bool,
) -> None:
    sec = container.get("securityContext")
    sec = sec if isinstance(sec, dict) else {}

    def effective(key: str) -> Any:
        return sec.get(key, pod_security.get(key))

    image = container.get("image")
    if isinstance(image, str):
        _image_findings(report, where, image)
    else:
        report.add("latest-tag", f"{where}: no image reference")
    run_user = effective("runAsUser")
    non_root = effective("runAsNonRoot") is True or (
        isinstance(run_user, int) and not isinstance(run_user, bool) and run_user > 0
    )
    if run_user == 0 or effective("runAsNonRoot") is False or not non_root:
        report.add("run-as-root", f"{where}: not forced to a non-root user")
    if sec.get("privileged") is True:
        report.add("privileged", f"{where}: privileged: true")
    escalation = sec.get("allowPrivilegeEscalation")
    if escalation is True:
        report.add("privilege-escalation", f"{where}: allowPrivilegeEscalation: true")
    elif escalation is not False:
        report.add(
            "missing-no-new-privileges",
            f"{where}: allowPrivilegeEscalation is not set to false",
        )
    if sec.get("readOnlyRootFilesystem") is not True:
        report.add("writable-rootfs", f"{where}: readOnlyRootFilesystem is not true")
    resources = container.get("resources")
    limits = resources.get("limits") if isinstance(resources, dict) else None
    if not (isinstance(limits, dict) and "memory" in limits):
        report.add("missing-resource-limits", f"{where}: no memory limit is set")
    if probes:
        missing = [
            key
            for key in ("livenessProbe", "readinessProbe")
            if not isinstance(container.get(key), dict)
        ]
        if missing:
            report.add("missing-probe", f"{where}: missing {', '.join(missing)}")
    env = container.get("env")
    if isinstance(env, list):
        for item in env:
            if isinstance(item, dict) and "valueFrom" not in item and "name" in item:
                report.secret_env(where, str(item["name"]), item.get("value"))
    report.secret_args(where, _words(container.get("args")))
    report.secret_args(where, _words(container.get("command")))


def _check_k8s_doc(doc: dict[str, Any], report: _Report) -> None:
    kind = doc.get("kind")
    meta = doc.get("metadata")
    label = f"{kind} {meta.get('name', '?')}" if isinstance(meta, dict) else str(kind)
    if kind == "Secret":
        for field in ("data", "stringData"):
            if doc.get(field):
                report.add(
                    "inline-secret", f"{label}: {field} holds inline secret values"
                )
        return
    spec = _pod_spec(doc)
    if spec is None:
        return
    if spec.get("hostNetwork") is True:
        report.add("host-network", f"{label}: hostNetwork: true")
    if spec.get("hostPID") is True:
        report.add("host-pid", f"{label}: hostPID: true")
    pod_security = spec.get("securityContext")
    pod_security = pod_security if isinstance(pod_security, dict) else {}
    for field, probes in (("containers", True), ("initContainers", False)):
        entries = spec.get(field)
        if not isinstance(entries, list):
            continue
        for entry in entries:
            if isinstance(entry, dict):
                where = f"{label} {field[:-1]} {entry.get('name', '?')}"
                _k8s_container(report, where, entry, pod_security, probes=probes)


# --- driver

_DOCKER_NAMES = re.compile(r"^(?:Dockerfile(?:\..+)?|.+\.Dockerfile)$")
_SUFFIXES = (".yaml", ".yml", ".service")


def _candidate(path: Path) -> bool:
    return bool(_DOCKER_NAMES.match(path.name)) or path.suffix in _SUFFIXES


def _kind_of(path: Path, text: str) -> str | None:
    if path.suffix not in (".yaml", ".yml", ".service") and (
        _DOCKER_NAMES.match(path.name) or re.search(r"(?m)^FROM\s+\S", text)
    ):
        return "docker"
    if re.search(r"(?m)^\[Service\]\s*$", text):
        return "systemd"
    if path.suffix in (".yaml", ".yml"):
        return "yaml"
    return None


def _analyze(
    path: Path, label: str, *, explicit: bool
) -> tuple[list[Finding], list[dict[str, Any]], bool]:
    """Findings for one file, its k8s documents, and whether it is a workload file."""
    report = _Report(label)
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        report.add("unparseable", f"cannot read the file: {exc}")
        return report.findings, [], False
    kind = _kind_of(path, text)
    k8s_docs: list[dict[str, Any]] = []
    workload = False
    if kind == "docker":
        _check_docker(text, report)
    elif kind == "systemd":
        _check_systemd(text, report)
    elif kind == "yaml":
        try:
            docs = _load_yaml(text)
        except _YamlError as exc:
            report.add("unparseable", f"cannot read this YAML: {exc}")
            return report.findings, [], False
        recognized = False
        for doc in docs:
            if not isinstance(doc, dict):
                continue
            if isinstance(doc.get("services"), dict):
                recognized = True
                _check_compose(doc, report)
            elif "kind" in doc and "apiVersion" in doc:
                recognized = True
                _check_k8s_doc(doc, report)
                k8s_docs.append(doc)
                workload = workload or _pod_spec(doc) is not None
        if not recognized and explicit:
            report.add("unrecognized-file", "no compose services or Kubernetes objects")
    elif explicit:
        report.add(
            "unrecognized-file", "not a Dockerfile, compose, Kubernetes or unit file"
        )
    if kind is not None:
        report.scan_text(text)
    return report.findings, k8s_docs, workload


def _is_promotion_name(name: str) -> bool:
    """True when a file name marks the set as a production promotion."""
    base = name.lower()
    return base.startswith(("promot", "prod-", "prod_", "prod."))


def _is_staging_evidence(name: str) -> bool:
    """True for a staging receipt or an image digest file."""
    base = name.lower()
    return "staging" in base or base.endswith(".digest")


def _is_approval_record(name: str) -> bool:
    """True for a promotion approval or audit record file."""
    base = name.lower()
    return "approv" in base or "audit" in base


def _promotion_findings(peers: list[tuple[Path, str]]) -> list[Finding]:
    """Staging-first gate: a promotion marker without evidence warns, never errors."""
    promotion: str | None = None
    staging = False
    approval = False
    for file_path, label in peers:
        name = file_path.name
        if promotion is None and _is_promotion_name(name):
            promotion = label
        if _is_staging_evidence(name):
            staging = True
        if _is_approval_record(name):
            approval = True
    if promotion is None:
        return []
    findings: list[Finding] = []
    if not staging:
        findings.append(
            Finding(
                "promote-without-staging-evidence",
                "warning",
                promotion,
                "production promotion has no staging receipt or image digest; "
                "verify on staging first",
            )
        )
    if not approval:
        findings.append(
            Finding(
                "missing-promotion-approval-record",
                "warning",
                promotion,
                "production promotion has no approval or audit record",
            )
        )
    return findings


def check(path: str | Path) -> list[Finding]:
    """Scan a file or a directory of artifacts. Raises `FileNotFoundError` for a bad path."""
    root = Path(path)
    if not root.exists():
        raise FileNotFoundError(f"no such file or directory: {root}")
    findings: list[Finding] = []
    if root.is_dir():
        targets = [
            (p, p.relative_to(root).as_posix())
            for p in sorted(root.rglob("*"))
            if p.is_file() and _candidate(p)
        ]
        explicit = False
    else:
        targets = [(root, root.name)]
        explicit = True
    policies = 0
    first_workload: str | None = None
    for file_path, label in targets:
        file_findings, docs, workload = _analyze(file_path, label, explicit=explicit)
        findings.extend(file_findings)
        policies += sum(1 for d in docs if d.get("kind") == "NetworkPolicy")
        if workload and first_workload is None:
            first_workload = label
    if first_workload is not None and policies == 0:
        findings.append(
            Finding(
                "missing-network-policy",
                "warning",
                first_workload,
                "no NetworkPolicy restricts ingress to the workload",
            )
        )
    if root.is_dir():
        peers = [
            (p, p.relative_to(root).as_posix())
            for p in sorted(root.rglob("*"))
            if p.is_file()
        ]
    else:
        peers = [(root, root.name)]
        with contextlib.suppress(OSError):
            peers += [
                (p, p.name)
                for p in sorted(root.parent.iterdir())
                if p.is_file() and p != root
            ]
    findings.extend(_promotion_findings(peers))
    return sorted(
        findings, key=lambda f: (f.file, f.severity != "error", f.id, f.message)
    )


# ------------------------------------------------- rollout, healthcheck, promote

# Release rollout mode, read from the environment by `promote`. `staged` is the
# default: the digest must first appear with staging evidence before it is
# accepted. `direct` skips the staging wait but needs both the environment
# variable AND the --direct flag, so one stray setting cannot skip staging.
ROLLOUT_ENV_VAR = "OMEGA_PRIME_IMAGE_ROLLOUT"
ROLLOUT_MODES = ("staged", "direct")

# One identifier chains build -> approval -> promote: the publish job digest.
_DIGEST_RE = re.compile(r"\Asha256:[0-9a-f]{64}\Z")
_DIGEST_SEARCH_RE = re.compile(r"sha256:[0-9a-f]{64}")

# Probe paths served by every rendered target (see the k8s liveness/readiness
# probes and the Docker/compose /healthz healthchecks).
_HEALTH_PATHS = ("/healthz", "/readyz")
_PROBE_TIMEOUT = 3.0
_PROBE_DELAY = 0.1

# Evidence files chain promotions: each one records the digest it promoted and
# the digest it superseded, so a rollback re-promotes a recorded digest.
_EVIDENCE_GLOB = "*promotion*evidence*.json"


def _read_rollout_mode() -> str:
    """Rollout mode from the environment; unknown values fall back to staged."""
    mode = os.environ.get(ROLLOUT_ENV_VAR, "staged").strip().lower() or "staged"
    return mode if mode in ROLLOUT_MODES else "staged"


def _digest_tokens(text: str) -> set[str]:
    """Every publish-digest token in a blob of text."""
    return set(_DIGEST_SEARCH_RE.findall(text))


def _newest_evidence(directory: Path) -> Path | None:
    """Newest promotion evidence file in `directory`, or None on first promotion."""
    matches = sorted(directory.glob(_EVIDENCE_GLOB))
    return matches[-1] if matches else None


def _resolve_probe_port(target: str, directory: Path) -> int:
    """Port the rendered target serves probes on; DEFAULT_PORT when unresolvable."""
    patterns = (
        r"containerPort\s*:\s*(\d+)",
        r"EXPOSE\s+(\d+)",
        r"--port[= ](\d+)",
        r"127\.0\.0\.1:(\d+):",
    )
    for path in sorted(directory.rglob("*")):
        if not path.is_file():
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        for pattern in patterns:
            match = re.search(pattern, text)
            if match:
                try:
                    port = int(match.group(1))
                except ValueError:
                    continue
                if 1 <= port <= 65535:
                    return port
    return DEFAULT_PORT


def _probe_attempts(directory: Path) -> int:
    """Per-probe attempts from the rendered retry budget (failureThreshold/retries).

    The total per-probe time (attempts x timeout) stays inside the rendered
    budget (k8s periodSeconds x failureThreshold, Docker interval x retries).
    """
    attempts = 0
    for path in sorted(directory.rglob("*")):
        if not path.is_file():
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        for pattern in (r"failureThreshold\s*:\s*(\d+)", r"--retries[= ](\d+)"):
            for match in re.finditer(pattern, text):
                with contextlib.suppress(ValueError):
                    attempts = max(attempts, int(match.group(1)))
    # Clamped to 3: the k8s startupProbe failureThreshold (30) is a slow-start
    # allowance, not a per-probe retry count, so it must not inflate attempts.
    return min(max(attempts or 3, 1), 3)


def _probe_url(url: str, *, timeout: float = _PROBE_TIMEOUT) -> bool:
    """True when one probe GET returns 200; any failure or other status is False."""
    try:
        with urllib.request.urlopen(url, timeout=timeout) as response:
            return response.status == 200
    except OSError:
        return False


def healthcheck(
    target: str,
    directory: str | Path,
    *,
    probe: Callable[[str], bool] | None = None,
) -> int:
    """Probe the rendered /healthz then /readyz paths; 0 only when both pass.

    Returns 2 when the target is unknown or the directory cannot be resolved,
    1 on the first failed probe after the rendered retry budget is spent.
    `probe` is an injectable single-GET seam (takes the probe URL, returns
    True on HTTP 200); the default is the stdlib urllib probe used in
    production. Tests MUST pass a scripted probe — never a live socket.
    """
    if target not in TARGETS:
        print(f"deploy: unknown target {target!r}", file=sys.stderr)
        return 2
    root = Path(directory)
    if not root.is_dir():
        print(f"deploy: no such directory: {root}", file=sys.stderr)
        return 2
    entries = [p for p in sorted(root.rglob("*")) if p.is_file()]
    if not entries:
        print(f"deploy: no files to resolve probes from: {root}", file=sys.stderr)
        return 2
    port = _resolve_probe_port(target, root)
    attempts = _probe_attempts(root)
    probe_fn = _probe_url if probe is None else probe
    for probe_path in _HEALTH_PATHS:
        url = f"http://127.0.0.1:{port}{probe_path}"
        passed = False
        for attempt in range(attempts):
            if probe_fn(url):
                passed = True
                break
            if attempt + 1 < attempts:
                time.sleep(_PROBE_DELAY)
        if not passed:
            print(
                f"deploy: healthcheck {target} {probe_path} failed "
                f"(port {port}, {attempts} attempt(s))",
                file=sys.stderr,
            )
            return 1
    print(f"deploy: healthcheck {target} ok (port {port})")
    return 0


def promote(
    digest: str,
    directory: str | Path,
    approval: str | Path,
    *,
    direct: bool = False,
) -> int:
    """Promote one publish digest with staging-first evidence; never rebuilds.

    Staged (default) refuses without a staging receipt (*staging*) or image
    digest (*.digest) file in the directory. Direct additionally requires BOTH
    OMEGA_PRIME_IMAGE_ROLLOUT=direct and direct=True. A supplied digest that
    does not match the .digest file content refuses. On success writes a
    promotion evidence JSON chaining promoted/previous digest, approval, and
    timestamp, and prints its path. Returns 0 on success, 1 on gate refusal,
    2 on bad usage.
    """
    if not _DIGEST_RE.match(digest or ""):
        print(
            "deploy: digest must be a publish digest (sha256:<64 hex>)",
            file=sys.stderr,
        )
        return 2
    root = Path(directory)
    if not root.is_dir():
        print(f"deploy: no such directory: {root}", file=sys.stderr)
        return 2
    record = Path(approval)
    if not record.is_file():
        print(f"deploy: no such approval record: {record}", file=sys.stderr)
        return 2
    mode = _read_rollout_mode()
    if direct and mode != "direct":
        print(
            f"deploy: --direct requires {ROLLOUT_ENV_VAR}=direct "
            f"(current mode: {mode})",
            file=sys.stderr,
        )
        return 1
    if mode == "direct" and not direct:
        print(
            f"deploy: direct promotion requires both {ROLLOUT_ENV_VAR}=direct "
            "and the --direct flag",
            file=sys.stderr,
        )
        return 1
    peers = [p for p in sorted(root.rglob("*")) if p.is_file()]
    if not any(_is_staging_evidence(p.name) for p in peers):
        print(
            "deploy: staged promotion refused: no staging receipt (*staging*) "
            "or image digest (*.digest) file in the directory",
            file=sys.stderr,
        )
        return 1
    approval_ok = any(_is_approval_record(p.name) for p in peers) or (
        _is_approval_record(record.name)
    )
    if not approval_ok:
        print(
            "deploy: staged promotion refused: no approval (*approv*) or audit "
            "(*audit*) record",
            file=sys.stderr,
        )
        return 1
    known: set[str] = set()
    unreadable: list[str] = []
    for path in peers:
        if not path.name.lower().endswith(".digest"):
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            unreadable.append(path.name)
            continue
        tokens = _digest_tokens(text)
        if not tokens:
            # Present but empty or malformed: fail closed, never silently
            # skip — otherwise any supplied digest would succeed.
            unreadable.append(path.name)
            continue
        known |= tokens
    if unreadable:
        print(
            "deploy: promotion refused: unreadable or malformed .digest file "
            f"({', '.join(sorted(unreadable))}); refusing fail-closed rather "
            "than promoting without digest evidence",
            file=sys.stderr,
        )
        return 1
    if known and digest not in known:
        print(
            "deploy: promotion refused: digest does not match the .digest file; "
            "promote the approved digest verbatim, never rebuild",
            file=sys.stderr,
        )
        return 1
    previous: str | None = None
    newest = _newest_evidence(root)
    if newest is not None:
        try:
            prior = json.loads(newest.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, ValueError):
            prior = {}
        if isinstance(prior, dict) and isinstance(prior.get("promoted_digest"), str):
            previous = prior["promoted_digest"]
    try:
        approval_text = record.read_text(encoding="utf-8").strip()
    except (OSError, UnicodeDecodeError) as exc:
        print(f"deploy: cannot read approval record: {exc}", file=sys.stderr)
        return 2
    if not any(p.name == record.name for p in peers if p.parent == root):
        dest_name = (
            record.name
            if _is_approval_record(record.name)
            else f"approval-{record.name}"
        )
        dest = root / dest_name
        if not dest.exists():
            with contextlib.suppress(OSError):
                shutil.copyfile(record, dest)
    stamp = datetime.datetime.now(datetime.UTC)
    evidence = {
        "promoted_digest": digest,
        "previous_digest": previous,
        "approval": {"record": record.name, "content": approval_text},
        "rollout": "direct" if mode == "direct" else "staged",
        "timestamp": stamp.strftime("%Y-%m-%dT%H:%M:%SZ"),
    }
    out_name = f"promotion-evidence-{stamp.strftime('%Y%m%dT%H%M%S%fZ')}.json"
    out_path = root / out_name
    try:
        out_path.write_text(json.dumps(evidence, indent=2, sort_keys=True) + "\n")
    except OSError as exc:
        print(f"deploy: cannot write evidence: {exc}", file=sys.stderr)
        return 2
    print(str(out_path))
    return 0


