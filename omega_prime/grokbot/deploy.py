def _validate(
    *, name: str, image: str, port: int, public_url: str | None, uid: int
) -> None:
    if not isinstance(name, str) or not _NAME_RE.match(name):
        raise DeployError(f"name {name!r} is not a DNS label (a-z, 0-9, '-', <= 63)")
    if not isinstance(image, str) or len(image) > 255 or not _IMAGE_RE.match(image):
        raise DeployError(f"image {image!r} is not a valid image reference")
    if isinstance(port, bool) or not isinstance(port, int) or not 1 <= port <= 65535:
        raise DeployError(f"port {port!r} must be an integer 1-65535")
    if isinstance(uid, bool) or not isinstance(uid, int) or uid < 1000:
        raise DeployError(f"uid {uid!r} must be an integer >= 1000")
    if public_url is not None and (
        not isinstance(public_url, str) or not _URL_RE.match(public_url)
    ):
        raise DeployError("public_url must be an http(s) URL without spaces or quotes")


def _server_args(
    *,
    root: str,
    host: str,
    port: int,
    token_file: str,
    audit_log: str,
    home: str,
    public_url: str | None,
) -> list[str]:
    args = [
        "--root",
        root,
        "--transport",
        "sse",
        "--host",
        host,
        "--port",
        str(port),
        "--token-file",
        token_file,
        "--audit-log",
        audit_log,
        "--home",
        home,
        "--shutdown-grace",
        str(SHUTDOWN_GRACE),
        "--log-format",
        "json",
    ]
    if public_url:
        args = [*args, "--public-url", public_url]
    return args


