def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m omega_prime.grokbot.deploy",
        description="Render and check hardened deployment artifacts.",
    )
    sub = parser.add_subparsers(dest="command", required=True)
    render_cmd = sub.add_parser("render", help="write the artifacts of one target")
    render_cmd.add_argument("--target", required=True, choices=TARGETS)
    render_cmd.add_argument("--out", required=True, type=Path, metavar="DIR")
    render_cmd.add_argument("--name", default=DEFAULT_NAME)
    render_cmd.add_argument("--image", default=DEFAULT_IMAGE)
    render_cmd.add_argument("--port", type=int, default=DEFAULT_PORT)
    render_cmd.add_argument("--public-url", default=None, metavar="URL")
    render_cmd.add_argument("--uid", type=int, default=DEFAULT_UID)
    render_cmd.add_argument(
        "--force", action="store_true", help="replace files this tool did not generate"
    )
    check_cmd = sub.add_parser("check", help="scan artifacts for hardening findings")
    check_cmd.add_argument("path", type=Path)
    check_cmd.add_argument(
        "--json", action="store_true", help="machine-readable output"
    )
    health_cmd = sub.add_parser(
        "healthcheck", help="probe the rendered /healthz and /readyz paths"
    )
    health_cmd.add_argument("--target", required=True, choices=TARGETS)
    health_cmd.add_argument("--dir", required=True, type=Path, metavar="DIR")
    promote_cmd = sub.add_parser(
        "promote", help="promote one publish digest with staging-first evidence"
    )
    promote_cmd.add_argument("--digest", required=True, metavar="sha256:...")
    promote_cmd.add_argument("--dir", required=True, type=Path, metavar="DIR")
    promote_cmd.add_argument("--approval", required=True, type=Path, metavar="RECORD")
    promote_cmd.add_argument(
        "--direct",
        action="store_true",
        help=f"allow direct promotion (also requires {ROLLOUT_ENV_VAR}=direct)",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """CLI entry. Exit 0 clean or warnings only, 1 on an error finding, 2 on bad usage."""
    parser = _build_parser()
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:
        return exc.code if isinstance(exc.code, int) else 2
    if args.command == "render":
        try:
            paths = render(
                args.target,
                args.out,
                name=args.name,
                image=args.image,
                port=args.port,
                public_url=args.public_url,
                uid=args.uid,
                overwrite=args.force,
            )
        except (DeployError, OSError) as exc:
            print(f"deploy: {exc}", file=sys.stderr)
            return 2
        for path in paths:
            print(path)
        return 0
    if args.command == "healthcheck":
        return healthcheck(args.target, args.dir)
    if args.command == "promote":
        return promote(args.digest, args.dir, args.approval, direct=args.direct)
    try:
        findings = check(args.path)
    except OSError as exc:
        print(f"deploy: {exc}", file=sys.stderr)
        return 2
    errors = sum(1 for f in findings if f.severity == "error")
    if args.json:
        payload = {
            "ok": errors == 0,
            "errors": errors,
            "warnings": len(findings) - errors,
            "findings": [f.to_dict() for f in findings],
        }
        print(json.dumps(payload, indent=2, sort_keys=True))
    else:
        for f in findings:
            print(f"{f.file}: {f.severity} [{f.id}] {f.message}")
        print(f"{errors} error(s), {len(findings) - errors} warning(s)")
    return 1 if errors else 0


