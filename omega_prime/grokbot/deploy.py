def _sd_quote(arg: str) -> str:
    """Quote one ExecStart word. Callers escape `%` and `$` in user data first."""
    if arg and not re.search(r"[\s\"'\\;]", arg):
        return arg
    return '"' + arg.replace("\\", "\\\\").replace('"', '\\"') + '"'


