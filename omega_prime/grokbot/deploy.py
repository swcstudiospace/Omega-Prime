# --- YAML emitter (deterministic block style; strings are always JSON-quoted)

_PLAIN_KEY = re.compile(r"^[A-Za-z_][A-Za-z0-9_./-]*$")
_FLOW_LIMIT = 76


def _scalar(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value)
    raise TypeError(f"cannot emit {type(value).__name__}")


def _key(key: str) -> str:
    return key if _PLAIN_KEY.match(key) else json.dumps(key)


def _is_scalar(value: Any) -> bool:
    return value is None or isinstance(value, (bool, int, str))


def _emit(value: Any, indent: int = 0) -> list[str]:
    pad = " " * indent
    lines: list[str] = []
    if isinstance(value, dict):
        for key, item in value.items():
            head = f"{pad}{_key(key)}:"
            if _is_scalar(item):
                lines.append(f"{head} {_scalar(item)}")
            elif isinstance(item, dict):
                lines.extend(
                    [f"{head} {{}}"] if not item else [head, *_emit(item, indent + 2)]
                )
            elif not item:
                lines.append(f"{head} []")
            elif all(_is_scalar(x) for x in item):
                flow = "[" + ", ".join(_scalar(x) for x in item) + "]"
                if len(head) + 1 + len(flow) <= _FLOW_LIMIT:
                    lines.append(f"{head} {flow}")
                else:
                    lines.extend([head, *_emit(item, indent + 2)])
            else:
                lines.extend([head, *_emit(item, indent + 2)])
        return lines
    for item in value:
        if _is_scalar(item):
            lines.append(f"{pad}- {_scalar(item)}")
            continue
        inner = _emit(item, indent + 2)
        lines.append(f"{pad}- {inner[0].lstrip()}")
        lines.extend(inner[1:])
    return lines


def _is_generated(path: Path) -> bool:
    try:
        with path.open(encoding="utf-8") as handle:
            head = [handle.readline() for _ in range(4)]
    except (OSError, UnicodeDecodeError):
        return False
    return any(GENERATED_MARKER in line for line in head)


def render(
    target: str,
    out_dir: str | Path,
    *,
    name: str = DEFAULT_NAME,
    image: str = DEFAULT_IMAGE,
    port: int = DEFAULT_PORT,
    public_url: str | None = None,
    uid: int = DEFAULT_UID,
    overwrite: bool = False,
) -> list[Path]:
    """Write the artifacts of `target` into `out_dir` and return their paths.

    Output is deterministic: the same arguments always produce the same bytes. A
    file this function did not generate is never replaced unless `overwrite`.
    """
    if target not in TARGETS:
        raise DeployError(
            f"unknown target {target!r}; choose from {', '.join(TARGETS)}"
        )
    _validate(name=name, image=image, port=port, public_url=public_url, uid=uid)
    files: dict[str, str]
    if target == "docker":
        files = {
            "Dockerfile": _render_dockerfile(
                name=name, port=port, public_url=public_url, uid=uid
            ),
            ".dockerignore": _render_dockerignore(),
        }
    elif target == "compose":
        files = {
            "compose.yaml": _render_compose(
                name=name, image=image, port=port, public_url=public_url, uid=uid
            )
        }
    elif target == "systemd":
        files = {
            f"{name}.service": _render_systemd(
                name=name, port=port, public_url=public_url, uid=uid
            )
        }
    else:
        files = {
            f"{name}.yaml": _render_k8s(
                name=name, image=image, port=port, public_url=public_url, uid=uid
            )
        }
    out = Path(out_dir)
    if out.exists() and not out.is_dir():
        raise DeployError(f"{out} exists and is not a directory")
    paths = [out / filename for filename in files]
    if not overwrite:
        for path in paths:
            if path.exists() and not (path.is_file() and _is_generated(path)):
                raise DeployError(
                    f"{path} exists and was not generated by this tool; "
                    "use --force to replace it"
                )
    out.mkdir(parents=True, exist_ok=True)
    for path, text in zip(paths, files.values(), strict=True):
        atomic_write_text(path, text, mode=0o644)
    return paths


# --------------------------------------------------------------------------- YAML subset reader


class _YamlError(ValueError):
    pass


class _Line(NamedTuple):
    indent: int
    text: str  # comment-stripped, right-trimmed
    raw: str
    blank: bool


def _strip_comment(text: str) -> str:
    quote = ""
    i = 0
    while i < len(text):
        ch = text[i]
        if quote:
            if quote == '"' and ch == "\\":
                i += 2
                continue
            if ch == quote:
                quote = ""
        elif ch in "\"'" and (i == 0 or text[i - 1] in " \t[{,:-"):
            quote = ch
        elif ch == "#" and (i == 0 or text[i - 1] in " \t"):
            return text[:i].rstrip()
        i += 1
    return text.rstrip()


def _prepare_lines(raw_lines: list[str]) -> list[_Line]:
    out: list[_Line] = []
    for raw in raw_lines:
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            out.append(_Line(0, "", raw, True))
            continue
        body = raw.lstrip(" ")
        if body.startswith("\t"):
            raise _YamlError("tab indentation is not supported")
        text = _strip_comment(body)
        out.append(_Line(len(raw) - len(body), text, raw, not text))
    return out


def _quoted_end(text: str, start: int) -> int:
    quote = text[start]
    i = start + 1
    while i < len(text):
        ch = text[i]
        if quote == '"' and ch == "\\":
            i += 2
            continue
        if ch == quote:
            if quote == "'" and text[i + 1 : i + 2] == "'":
                i += 2
                continue
            return i
        i += 1
    raise _YamlError("unterminated quoted string")


def _unquote(token: str) -> str:
    if token[0] == '"':
        try:
            value = json.loads(token)
        except ValueError:
            return token[1:-1]
        return str(value)
    return token[1:-1].replace("''", "'")


_INT_RE = re.compile(r"^-?\d+$")


def _plain(token: str) -> Any:
    if token in ("", "~", "null", "Null", "NULL"):
        return None
    if token in ("true", "True", "TRUE"):
        return True
    if token in ("false", "False", "FALSE"):
        return False
    if _INT_RE.match(token):
        return int(token)
    return token


def _flow(text: str, pos: int, *, in_map_key: bool = False) -> tuple[Any, int]:
    while pos < len(text) and text[pos] == " ":
        pos += 1
    if pos >= len(text):
        raise _YamlError("unexpected end of flow collection")
    ch = text[pos]
    if ch == "[":
        items: list[Any] = []
        pos += 1
        while True:
            while pos < len(text) and text[pos] == " ":
                pos += 1
            if pos >= len(text):
                raise _YamlError("unterminated flow list")
            if text[pos] == "]":
                return items, pos + 1
            value, pos = _flow(text, pos)
            items.append(value)
            while pos < len(text) and text[pos] == " ":
                pos += 1
            if pos < len(text) and text[pos] == ",":
                pos += 1
            elif pos >= len(text) or text[pos] != "]":
                raise _YamlError("bad flow list")
    if ch == "{":
        result: dict[str, Any] = {}
        pos += 1
        while True:
            while pos < len(text) and text[pos] == " ":
                pos += 1
            if pos >= len(text):
                raise _YamlError("unterminated flow map")
            if text[pos] == "}":
                return result, pos + 1
            key, pos = _flow(text, pos, in_map_key=True)
            while pos < len(text) and text[pos] == " ":
                pos += 1
            if pos >= len(text) or text[pos] != ":":
                raise _YamlError("bad flow map")
            value, pos = _flow(text, pos + 1)
            result[str(key)] = value
            while pos < len(text) and text[pos] == " ":
                pos += 1
            if pos < len(text) and text[pos] == ",":
                pos += 1
            elif pos >= len(text) or text[pos] != "}":
                raise _YamlError("bad flow map")
    if ch in ('"', "'"):
        end = _quoted_end(text, pos)
        return _unquote(text[pos : end + 1]), end + 1
    stops = ",]}:" if in_map_key else ",]}"
    end = pos
    while end < len(text) and text[end] not in stops:
        end += 1
    return _plain(text[pos:end].strip()), end


def _scalar_from_text(text: str) -> Any:
    text = text.strip()
    if text[:1] in ("&", "*", "!") or text.startswith("<<"):
        raise _YamlError("anchors, aliases and tags are not supported")
    if text[:1] in ("[", "{"):
        value, pos = _flow(text, 0)
        if text[pos:].strip():
            raise _YamlError("trailing text after flow collection")
        return value
    if text[:1] in ('"', "'"):
        end = _quoted_end(text, 0)
        if text[end + 1 :].strip():
            raise _YamlError("trailing text after quoted string")
        return _unquote(text[: end + 1])
    return _plain(text)


def _split_key(text: str) -> tuple[str, str] | None:
    """Split `key: rest`; None when `text` is not a mapping entry."""
    if text[:1] in ("[", "{"):
        return None
    if text[:1] in ('"', "'"):
        end = _quoted_end(text, 0)
        after = text[end + 1 :]
        if after.startswith(":") and (len(after) == 1 or after[1] == " "):
            return _unquote(text[: end + 1]), after[1:].strip()
        return None
    if text.endswith(":"):
        return text[:-1].rstrip(), ""
    idx = text.find(": ")
    if idx < 0:
        return None
    return text[:idx].rstrip(), text[idx + 2 :].strip()


def _is_item(text: str) -> bool:
    return text == "-" or text.startswith("- ")


_BLOCK_MARKERS = {"|", "|-", "|+", ">", ">-", ">+"}


class _Reader:
    def __init__(self, lines: list[_Line]) -> None:
        self.lines = lines
        self.i = 0

    def peek(self) -> _Line | None:
        while self.i < len(self.lines) and self.lines[self.i].blank:
            self.i += 1
        return self.lines[self.i] if self.i < len(self.lines) else None

    def node(self, indent: int) -> Any:
        line = self.peek()
        if line is None or line.indent < indent:
            return None
        if _is_item(line.text):
            return self.items(line.indent)
        return self.mapping(line.indent)

    def items(self, indent: int) -> list[Any]:
        result: list[Any] = []
        while True:
            line = self.peek()
            if line is None or line.indent != indent or not _is_item(line.text):
                return result
            rest = line.text[1:].lstrip(" ")
            if not rest:
                self.i += 1
                nxt = self.peek()
                result.append(
                    self.node(nxt.indent) if nxt and nxt.indent > indent else None
                )
                continue
            offset = len(line.text) - len(rest)
            self.lines[self.i] = line._replace(indent=indent + offset, text=rest)
            if _is_item(rest):
                result.append(self.items(indent + offset))
            elif _split_key(rest) is not None:
                result.append(self.mapping(indent + offset))
            else:
                self.i += 1
                result.append(_scalar_from_text(rest))

    def block_scalar(self, indent: int) -> str:
        collected: list[str] = []
        base: int | None = None
        while self.i < len(self.lines):
            line = self.lines[self.i]
            if line.blank:
                collected.append("")
                self.i += 1
                continue
            if line.indent <= indent:
                break
            base = line.indent if base is None else min(base, line.indent)
            collected.append(line.raw.rstrip("\n"))
            self.i += 1
        width = base or 0
        return "\n".join(x[width:] if x else "" for x in collected).rstrip("\n") + "\n"

    def mapping(self, indent: int) -> dict[str, Any]:
        result: dict[str, Any] = {}
        while True:
            line = self.peek()
            if line is None or line.indent < indent:
                return result
            if line.indent > indent:
                raise _YamlError(f"unexpected indentation: {line.text!r}")
            if _is_item(line.text):
                return result
            split = _split_key(line.text)
            if split is None:
                raise _YamlError(f"expected 'key: value', got {line.text!r}")
            key, rest = split
            if key == "<<":
                raise _YamlError("merge keys are not supported")
            if key in result:
                raise _YamlError(f"duplicate key {key!r}")
            self.i += 1
            value: Any
            if not rest:
                nxt = self.peek()
                if nxt is not None and nxt.indent > indent:
                    value = self.node(nxt.indent)
                elif nxt is not None and nxt.indent == indent and _is_item(nxt.text):
                    value = self.items(indent)
                else:
                    value = None
            elif rest in _BLOCK_MARKERS:
                value = self.block_scalar(indent)
            else:
                value = _scalar_from_text(rest)
            result[key] = value


def _load_yaml(text: str) -> list[Any]:
    """Parse a multi-document block-YAML subset. Raises `_YamlError` otherwise."""
    documents: list[list[str]] = [[]]
    for raw in text.splitlines():
        if raw.rstrip() == "---" or raw.startswith("--- "):
            documents.append([])
            continue
        if raw.rstrip() == "...":
            continue
        documents[-1].append(raw)
    result: list[Any] = []
    for raw_lines in documents:
        reader = _Reader(_prepare_lines(raw_lines))
        first = reader.peek()
        if first is None:
            continue
        value = reader.node(first.indent)
        if reader.peek() is not None:
            raise _YamlError("could not read the whole document")
        result.append(value)
    return result


